#!/usr/bin/env bash
# Writes src/types/supabase.ts: the TypeScript types of the public schema, made
# from supabase/migrations on the LOCAL database (issue #187). It never links to
# or reads the hosted project.
#
#   npm run db:types                  migrate a fresh local database, write the file
#   bash scripts/db/gen-types.sh --check
#                                     compare with a database that is already running
#                                     (CI: after `KEEP_DB=1 npm run test:db`); exit 1 when stale
#
# Without --check and without a running local database, the script starts one with
# scripts/db/test-migrations.sh (Docker, psql) and stops it at the end.
set -euo pipefail

cd "$(dirname "$0")/../.."

if [[ -x node_modules/.bin/supabase ]]; then SUPABASE=(node_modules/.bin/supabase); else SUPABASE=(supabase); fi
TARGET=src/types/supabase.ts
HEADER='// Generated by scripts/db/gen-types.sh from supabase/migrations. Do not edit; run npm run db:types.'

mode="write"
[[ "${1:-}" == "--check" ]] && mode="check"

started=0
if ! "${SUPABASE[@]}" status >/dev/null 2>&1; then
  [[ "$mode" == "check" ]] && { echo "No local database. Run KEEP_DB=1 npm run test:db first." >&2; exit 2; }
  KEEP_DB=1 bash scripts/db/test-migrations.sh >/dev/null
  started=1
fi
# shellcheck disable=SC2329 # invoked by the EXIT trap
cleanup() { if [[ "$started" == "1" ]]; then "${SUPABASE[@]}" stop --no-backup >/dev/null 2>&1 || true; fi; }
trap cleanup EXIT

generated="$(mktemp)"
{ echo "$HEADER"; "${SUPABASE[@]}" gen types typescript --local --schema public 2>/dev/null; } > "$generated"

if [[ "$mode" == "check" ]]; then
  if ! diff -u "$TARGET" "$generated"; then
    echo "::error file=$TARGET::$TARGET does not match supabase/migrations. Run npm run db:types and commit the file."
    exit 1
  fi
  echo "$TARGET matches supabase/migrations."
else
  mv "$generated" "$TARGET"
  echo "Wrote $TARGET."
fi
